#!/usr/bin/env python3
"""Regenerates Sources/True/Remote/RemoteWebAssets.swift from Resources/Remote/*.
True is a SwiftPM executable with no resource bundle, so the web app is embedded as base64 literals.
Run from the repo root:  python3 -I Resources/Remote/gen.py"""
import base64, pathlib
root = pathlib.Path(__file__).resolve().parent
files = {
    "/": ("index.html", "text/html; charset=utf-8"),
    "/app.js": ("app.js", "text/javascript; charset=utf-8"),
    "/app.css": ("app.css", "text/css; charset=utf-8"),
    "/xterm.js": ("xterm.js", "text/javascript; charset=utf-8"),
    "/xterm.css": ("xterm.css", "text/css; charset=utf-8"),
    "/manifest.webmanifest": ("manifest.webmanifest", "application/manifest+json"),
    "/icon.png": ("icon.png", "image/png"),
}
def b64(n): return base64.b64encode((root / n).read_bytes()).decode()
out = ["// GENERATED by Resources/Remote/gen.py — do not edit. xterm.js 5.5.0 (MIT), vendored locally, no CDN.",
       "import Foundation", "", "enum RemoteWebAssets {",
       "    struct Asset { let body: [UInt8]; let type: String }",
       "    private static func decode(_ s: String) -> [UInt8] { [UInt8](Data(base64Encoded: s) ?? Data()) }",
       "    private static let table: [String: (b64: String, type: String)] = ["]
for path, (name, typ) in files.items():
    out.append(f'        "{path}": ("{b64(name)}", "{typ}"),')
out += ["    ]",
        "",
        "    /// The app shell is not secret (all data is behind /api/* and the bearer token), so it is served after the identity check.",
        "    static func asset(_ path: String) -> Asset? {",
        "        let p = path == \"/index.html\" ? \"/\" : path",
        "        guard let e = table[p] else { return nil }",
        "        return Asset(body: decode(e.b64), type: e.type)",
        "    }", "}", ""]
(root.parent.parent / "Sources/True/Remote/RemoteWebAssets.swift").write_text("\n".join(out))

import Foundation
import AppKit

/// Opt-in: pushes text the user copies on this Mac into the phone inbox as the one "shared clipboard" item.
/// Push only — no route ever reads the Mac pasteboard on request. macOS has no pasteboard change
/// notification, so a 1 s timer on `changeCount` is the standard pattern; it runs only while sharing is on.
@MainActor
final class ClipboardShare {
    struct Snapshot {
        var changeCount: Int
        var types: [String]
        var text: String?
    }

    static let shared = ClipboardShare()
    /// Pasteboard flavours that mean "do not record this" (nspasteboard.org convention).
    static let skipTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                         "org.nspasteboard.AutoGeneratedType"]

    private let read: () -> Snapshot
    private let inbox: RemoteInbox
    private let interval: TimeInterval
    private var timer: Timer?
    private var lastChange: Int
    private var lastShared: String?

    var isRunning: Bool { timer != nil }

    init(read: @escaping () -> Snapshot = ClipboardShare.readGeneral, inbox: RemoteInbox = RemoteFilesLive.inbox,
         interval: TimeInterval = 1) {
        self.read = read; self.inbox = inbox; self.interval = interval
        lastChange = read().changeCount   // whatever is on the clipboard when sharing starts is not shared
    }

    nonisolated static func readGeneral() -> Snapshot {
        let pb = NSPasteboard.general
        return Snapshot(changeCount: pb.changeCount, types: pb.types?.map(\.rawValue) ?? [], text: pb.string(forType: .string))
    }

    func start() {
        guard timer == nil else { return }
        lastChange = read().changeCount
        let t = Timer(timeInterval: interval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.tick() }
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() { timer?.invalidate(); timer = nil }

    /// The phone's own push (`POST /api/clip`) sets the Mac pasteboard; remember it so it never echoes back.
    func noteExternal(_ text: String) { lastShared = text }

    func tick() {
        let snap = read()
        guard snap.changeCount != lastChange else { return }
        lastChange = snap.changeCount
        guard Self.skipTypes.isDisjoint(with: snap.types),
              let text = snap.text, !text.isEmpty, text.utf8.count <= RemoteFiles.maxClipBytes,
              text != lastShared else { return }
        lastShared = text
        inbox.replaceSharedClipboard(text: text)
    }
}
